def load_state_dict_flexible(model, pth):
    if not pth:
        return None

    if not os.path.isfile(pth):
        raise FileNotFoundError(f"PRETRAIN_PATH does not exist: {pth}")

    state = torch.load(pth, map_location="cuda" if torch.cuda.is_available() else "cpu")
    if isinstance(state, dict) and "state_dict" in state and isinstance(state["state_dict"], dict):
        state = state["state_dict"]
    elif isinstance(state, dict) and "model" in state and isinstance(state["model"], dict):
        state = state["model"]

    if isinstance(state, dict):
        keys = list(state.keys())
        if keys and all(k.startswith("module.") for k in keys):
            state = {k[len("module."):]: v for k, v in state.items()}

    result = model.load_state_dict(state, strict=False)
    print(f"===> Loaded checkpoint: {pth}")
    print(f"===> Missing keys: {len(result.missing_keys)}")
    print(f"===> Unexpected keys: {len(result.unexpected_keys)}")
    if result.missing_keys:
        print("===> First missing keys:", result.missing_keys[:20])
    if result.unexpected_keys:
        print("===> First unexpected keys:", result.unexpected_keys[:20])
    return result


