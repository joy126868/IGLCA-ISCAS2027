def train_one_epoch(epoch):
    model.train()
    loss_print = 0.0
    pic_cnt = 0
    train_len = len(training_data_loader)
    torch.autograd.set_detect_anomaly(opt.grad_detect)

    for iter_idx, batch in enumerate(tqdm(training_data_loader), start=1):
        im1, im2 = batch[0].cuda(), batch[1].cuda()

        if opt.gamma:
            gamma = random.randint(opt.start_gamma, opt.end_gamma) / 100.0
            output_rgb = model(im1 ** gamma)
        else:
            output_rgb = model(im1)

        gt_rgb = im2
        output_hvi = model.HVIT(output_rgb)
        gt_hvi = model.HVIT(gt_rgb)

        loss_hvi = (
            L1_loss(output_hvi, gt_hvi)
            + D_loss(output_hvi, gt_hvi)
            + E_loss(output_hvi, gt_hvi)
            + opt.P_weight * P_loss(output_hvi, gt_hvi)[0]
        )
        loss_rgb = (
            L1_loss(output_rgb, gt_rgb)
            + D_loss(output_rgb, gt_rgb)
            + E_loss(output_rgb, gt_rgb)
            + opt.P_weight * P_loss(output_rgb, gt_rgb)[0]
        )
        loss = loss_rgb + opt.HVI_weight * loss_hvi

        optimizer.zero_grad()
        loss.backward()
        if opt.grad_clip:
            torch.nn.utils.clip_grad_norm_(model.parameters(), 0.01, norm_type=2)
        optimizer.step()

        loss_print += loss.item()
        pic_cnt += 1

        if iter_idx == train_len:
            print(
                f"===> Epoch[{epoch}]: Loss: {loss_print / max(pic_cnt, 1):.4f} "
                f"|| Learning rate: lr={lr_report(optimizer)}."
            )
            training_vis_dir = os.path.join(opt.val_folder, "training", opt.dataset + "_" + RUN_TAG)
            os.makedirs(training_vis_dir, exist_ok=True)
            transforms.ToPILImage()(output_rgb[0].detach().cpu().clamp(0, 1).squeeze(0)).save(
                os.path.join(training_vis_dir, "test.png")
            )
            transforms.ToPILImage()(gt_rgb[0].detach().cpu().clamp(0, 1).squeeze(0)).save(
                os.path.join(training_vis_dir, "gt.png")
            )

    return loss_print, pic_cnt


def validate_and_record(epoch_label, metrics_md_path=None):
    os.makedirs(get_weights_dir(), exist_ok=True)

    model_out_path = os.path.join(get_weights_dir(), f"epoch_{epoch_label}.pth")
    torch.save(model.state_dict(), model_out_path)
    print(f"Checkpoint saved to {model_out_path}")

    output_folder, label_dir, norm_size = get_eval_config()
    output_dir = os.path.join(opt.val_folder, output_folder)
    im_dir = os.path.join(output_dir, "*.png")
    is_lol_v1 = opt.dataset == "lol_v1"
    is_lolv2_real = opt.dataset == "lolv2_real"

    eval(
        model,
        testing_data_loader,
        model_out_path,
        output_dir,
        norm_size=norm_size,
        LOL=is_lol_v1,
        v2=is_lolv2_real,
        alpha=0.8,
    )
    avg_psnr, avg_ssim, avg_lpips = metrics(im_dir, label_dir, use_GT_mean=False)

    print(f"===> [{RUN_TAG}] Avg.PSNR: {avg_psnr:.4f} dB")
    print(f"===> [{RUN_TAG}] Avg.SSIM: {avg_ssim:.4f}")
    print(f"===> [{RUN_TAG}] Avg.LPIPS: {avg_lpips:.4f}")

    if metrics_md_path is not None:
        with open(metrics_md_path, "a", encoding="utf-8") as f:
            f.write(f"| {epoch_label} | {avg_psnr:.4f} | {avg_ssim:.4f} | {avg_lpips:.4f} |\n")

    return {
        "epoch": epoch_label,
        "psnr": float(avg_psnr),
        "ssim": float(avg_ssim),
        "lpips": float(avg_lpips),
        "state_dict": copy.deepcopy(model.state_dict()),
    }


def is_better_result(curr, best):
    if best is None:
        return True
    if curr["psnr"] > best["psnr"] + 1e-12:
        return True
    if abs(curr["psnr"] - best["psnr"]) <= 1e-12 and curr["ssim"] > best["ssim"] + 1e-12:
        return True
    if (
        abs(curr["psnr"] - best["psnr"]) <= 1e-12
        and abs(curr["ssim"] - best["ssim"]) <= 1e-12
        and curr["lpips"] < best["lpips"] - 1e-12
    ):
        return True
    return False


