def ensure_ablation_module():
    """
    Generate net/CIDNet_LCA_NONE_BASELINE.py from net/CIDNet_IGLCA.py.

    This avoids modifying your original files.

    Target configuration:
        HV_LCA1~HV_LCA6: HV_LCA
        I_LCA1~I_LCA6  : I_LCA
    """
    src_path = Path("net") / "CIDNet_IGLCA.py"
    dst_path = Path("net") / "CIDNet_LCA_NONE_BASELINE.py"

    if not src_path.is_file():
        raise FileNotFoundError(
            "Cannot find net/CIDNet_IGLCA.py. "
            "Please run this script from your project root."
        )

    text = src_path.read_text(encoding="utf-8")

    replacements = [
        ("self.HV_LCA1 = IG_HV_LCA(ch2, head2)", "self.HV_LCA1 = HV_LCA(ch2, head2)"),
        ("self.HV_LCA2 = IG_HV_LCA(ch3, head3)", "self.HV_LCA2 = HV_LCA(ch3, head3)"),
        ("self.HV_LCA3 = IG_HV_LCA(ch4, head4)", "self.HV_LCA3 = HV_LCA(ch4, head4)"),
        ("self.HV_LCA4 = IG_HV_LCA(ch4, head4)", "self.HV_LCA4 = HV_LCA(ch4, head4)"),
        ("self.HV_LCA5 = IG_HV_LCA(ch3, head3)", "self.HV_LCA5 = HV_LCA(ch3, head3)"),
        ("self.HV_LCA6 = IG_HV_LCA(ch2, head2)", "self.HV_LCA6 = HV_LCA(ch2, head2)"),
        ("self.I_LCA1 = IG_I_LCA(ch2, head2)", "self.I_LCA1 = I_LCA(ch2, head2)"),
        ("self.I_LCA2 = IG_I_LCA(ch3, head3)", "self.I_LCA2 = I_LCA(ch3, head3)"),
        ("self.I_LCA3 = IG_I_LCA(ch4, head4)", "self.I_LCA3 = I_LCA(ch4, head4)"),
        ("self.I_LCA4 = IG_I_LCA(ch4, head4)", "self.I_LCA4 = I_LCA(ch4, head4)"),
        ("self.I_LCA5 = IG_I_LCA(ch3, head3)", "self.I_LCA5 = I_LCA(ch3, head3)"),
        ("self.I_LCA6 = IG_I_LCA(ch2, head2)", "self.I_LCA6 = I_LCA(ch2, head2)"),
    ]

    for old, new in replacements:
        text = text.replace(old, new)

    header_lines = [
        "# -*- coding: utf-8 -*-",
        "# AUTO-GENERATED by train_ablation_lca_none.py.",
        "# Ablation setting:",
        "#     LCA1-LCA6: original author LCA",
        "#     IG-LCA: disabled",
        "# Do not edit this file manually.",
        "",
    ]
    header = "\n".join(header_lines)

    if text.startswith("# -*- coding: utf-8 -*-"):
        text = "\n".join(text.splitlines()[1:])

    # ISCAS-2027 revision: DataLoader workers re-run this on every spawn (Windows); only write when the
    # content changes, so concurrent workers never read a half-written module.
    new_text = header + text
    if not (dst_path.is_file() and dst_path.read_text(encoding="utf-8") == new_text):
        dst_path.write_text(new_text, encoding="utf-8")
    print(f"===> Generated baseline module: {dst_path}")
    return dst_path


ensure_ablation_module()

